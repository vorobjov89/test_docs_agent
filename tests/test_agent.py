from app.agent.agent import ContractAgent


def main():
    agent = ContractAgent()

    query = """Покажи свёртку изменений договора D210262441-01:
какие дополнительные соглашения были заключены,
какие разделы и приложения они изменили,
каков тип каждого изменения и его содержание.
Укажи дату вступления изменений в силу и отдельно отметь изменения,
которые были извлечены, но не удалось применить
к структурированному состоянию договора."""

    print("=" * 80)
    print(f"QUERY: {query}")
    print("=" * 80)

    answer = agent.run(query)

    print("\n" + "=" * 80)
    print("ANSWER")
    print("=" * 80)
    print(answer)


if __name__ == "__main__":
    main()
