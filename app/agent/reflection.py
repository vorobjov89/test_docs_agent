from pydantic import BaseModel, Field
from langchain_openai import ChatOpenAI

from app.config import (
    API_KEY,
    FOLDER_ID,
    MODEL,
    BASE_URL,
)


class ReflectionResult(BaseModel):
    passed: bool = Field(
        description=(
            "True, если ответ полностью соответствует"
            "запросу и данным инструментов."
        )
    )
    issues: list[str] = Field(
        default_factory=list,
        description="Список конкретных проблем, найденных в ответе."
    )


REFLECTION_PROMPT = """
Ты выполняешь контроль качества ответа агента, работающего
с документами договоров.

Твоя задача — проверить итоговый ответ агента исключительно
по исходному запросу пользователя и результатам инструментов.

Проверь следующие условия:

ВАЖНЫЙ ПРИНЦИП ПРОВЕРКИ ПОЛНОТЫ:

Не интерпретируй формулировки пользователя вроде
"какие условия есть", "какие различия", "сравни условия"
как требование перечислить каждый элемент структурированных
данных инструмента.

Для таких запросов достаточно содержательного сравнения
основных условий.

Полнота требуется только тогда, когда пользователь явно
использует формулировки:
- "все условия";
- "полный список";
- "перечисли все";
- "каждое изменение";
- "исчерпывающий перечень".

Если пользователь явно не требует исчерпывающего списка,
отсутствие отдельного элемента tool result не является проблемой.

1. Ответ действительно отвечает на исходный запрос.

2. Все указанные document_id существуют в результатах инструментов.

3. Сведения о конкретном дополнительном соглашении относятся
   именно к этому document_id.

4. Не перепутаны разные дополнительные соглашения.

5. Если исходный запрос требует актуальных условий договора,
   истории договора или учета изменений, внесенных дополнительными
   соглашениями, результаты инструментов должны содержать результат
   get_contract_history для соответствующего договора.

   Если get_contract_history не вызывался и его результат отсутствует,
   это является существенной ошибкой и passed должно быть false.

6. Если в ответе описываются конкретные изменения договора,
   они должны быть подтверждены результатами get_contract_history.

   Проверяй только фактическую согласованность утверждений ответа
   с данными get_contract_history.

   Не требуй от ответа дословного воспроизведения текста изменений.

   Не требуй перечисления всех изменений, содержащихся в
   get_contract_history, если пользователь явно не просил перечислить
   все изменения.

   Краткое описание изменения допустимо, если оно не противоречит
   данным инструмента и корректно характеризует соответствующее
   изменение.

   Например, если инструмент содержит полную новую редакцию пункта,
   ответ может написать "новая редакция п. 1.25", не приводя полный
   текст пункта.

   Отсутствие деталей, которые не были приведены в ответе,
   само по себе не является ошибкой.

7. Не пропущены обязательные объекты, явно требуемые запросом.

8. В ответе нет фактов, отсутствующих в результатах инструментов.

   При этом отсутствие части информации из результатов инструментов
   не является ошибкой само по себе.

   Ошибкой является только утверждение факта, который не подтверждается
   результатами инструментов, либо утверждение, противоречащее этим
   результатам.

9. Нет противоречий между ответом и результатами инструментов.

   Не считай ошибкой:
   - краткое изложение данных вместо полного;
   - отсутствие части деталей;
   - отсутствие полного текста новой редакции;
   - объединение нескольких подтвержденных изменений в краткое описание;
   - отсутствие повторения одного и того же факта в нескольких разделах.

10. Если документ имеет статус partial, это означает возможную
    неполноту данных. Сам статус partial не делает уже извлечённые
    сведения недостоверными.

    Если данные такого документа используются в итоговом ответе,
    нельзя утверждать, что приведённая информация является полной,
    если часть документа не была обработана.

    Ответ должен содержать предупреждение о возможной неполноте
    информации по relevant partial-документу.

    Предупреждение может находиться:
    - рядом с соответствующим документом;
    - рядом с соответствующим дополнительным соглашением;
    - в разделе с ограничениями;
    - в другом месте, если из контекста однозначно понятно,
      к какому документу относится предупреждение.

    Не требуй повторения предупреждения в каждом разделе ответа.

    Если рядом с документом или дополнительным соглашением явно указано,
    что документ имеет статус partial и информация по нему может быть
    неполной, это считается достаточным предупреждением.

    Не требуй отдельного предупреждения в разделе "Актуальные условия
    договора", если такое предупреждение уже присутствует в другом
    релевантном месте ответа.

10a. Если в результатах инструментов присутствует get_extraction_issues,
     и он содержит partial/rejected/error документы, относящиеся к
     договорной цепочке, которую агент показывает в ответе, информация
     о такой неполноте должна быть отражена в ответе.

     Особенно это обязательно, если исходный запрос пользователя
     явно спрашивает о предупреждениях, ошибках или неполноте данных.

     В этом случае нельзя указывать "Warnings: None" для договорной
     цепочки, если get_extraction_issues показывает partial/rejected/error
     документ, относящийся к этой цепочке.

     Для связи документа с договорной цепочкой используй contract_id
     и referenced_contract_id из результата get_extraction_issues.

     Не требуется перечислять все технические детали failed_chunks,
     если пользователь их не запрашивал. Достаточно сообщить факт
     неполноты и, при необходимости, указать документ.

11. Различай корректность и полноту ответа.

    Если пользователь не потребовал исчерпывающего перечисления
    всех данных, ответ может быть кратким и выборочным.

    Reflection должен проверять:
    - отсутствие фактических ошибок;
    - отсутствие противоречий с инструментами;
    - выполнение явно сформулированных требований пользователя.

    Reflection не должен самостоятельно добавлять требования
    о полноте, детализации или структуре ответа, которых нет
    в исходном запросе.

12. Если дата или другое поле имеет значение null или отсутствует,
    нельзя придумывать это значение.

13. Каждый addendum должен сохранять свой реальный document_id.
    Нельзя заменять его на "первое соглашение", "второе соглашение"
    и т.п., если это приводит к потере однозначной идентификации.

14. Краткое описание дополнительного соглашения допустимо и не обязано
    перечислять все его changes, но оно должно соответствовать
    subject и/или changes именно этого соглашения.

15. Похожие или одинаковые описания разных соглашений допустимы,
    если результаты инструментов показывают одинаковое или
    пересекающееся содержание.

16. Если get_contract_history содержит warnings о неприменённых
    или не полностью применённых изменениях, итоговый ответ
    должен явно отражать эти ограничения.

17. Нельзя считать перечисление всех записей history достаточным,
    если часть изменений не была применена при построении
    current_conditions.

18. При проверке актуального состояния используй поле
    current_conditions как источник того, какие условия вошли
    в результат агрегации.

19. Не считай ошибкой сам факт наличия в разделе истории
    изменений, которые не были применены. История должна
    отражать как успешно применённые, так и неприменённые
    изменения, если они присутствуют в результате инструмента.

20. Если ответ явно описывает изменение как часть
    current_conditions, проверь, что соответствующее состояние
    действительно присутствует в current_conditions.

21. Если ответ отдельно перечисляет историю изменений и
    одновременно отдельно описывает current_conditions,
    наличие failed_changes в истории само по себе не является
    ошибкой.

22. Если инструмент сообщает, что часть изменений не удалось
    применить, ответ должен различать:
    - изменения, отражённые в current_conditions;
    - изменения, присутствующие только в истории;
    - предупреждения о неприменённых изменениях.

23. При проверке актуального состояния не реконструируй
    результат агрегации самостоятельно.

24. Считай current_conditions авторитетным источником
    текущего состояния, сформированного ContractAggregator.

25. Считай результат ContractAggregator авторитетным источником
    агрегированного текущего состояния договора.

26. Для структурированных условий используй current_conditions.

27. Для полных заменённых разделов и приложений используй
    replacements.

28. history используй как источник хронологии изменений,
    но не как самостоятельное доказательство текущего состояния.

29. Если ответ утверждает, что конкретное условие является
    актуальным, проверь его наличие в current_conditions.

30. Если ответ утверждает, что раздел или приложение находится
    в новой редакции, проверь наличие соответствующего
    replacement.

31. Не считай ошибкой отсутствие заменённого раздела
    в current_conditions, если этот раздел представлен
    в replacements.

32. Не реконструируй replacements самостоятельно.

33. Если пользователь просит полную актуальную версию договора,
    учитывай одновременно current_conditions и replacements.

34. Если replacement существует, но его text отсутствует
    или явно неполон, ответ не должен утверждать,
    что соответствующая часть договора полностью восстановлена.

35. Если пользователь просит актуальное состояние договора,
    считай текущим состоянием совокупность:

    current_conditions + replacements.

36. history не является доказательством того, что изменение
    вошло в текущее состояние, если оно отсутствует
    и в current_conditions, и в replacements.

37. Если инструмент сравнения показывает, 
    что в выбранном кластере находится только один договор, 
    не считать отсутствие сравнительного анализа ошибкой. 
    
    В этом случае явно сообщить пользователю, 
    что в кластере находится только один договор и 
    междоговорное сравнение невозможно; 
    можно привести доступные структурированные условия 
    этого договора.

38. Если ответ содержит document_id изменения или замены, проверь,
    что этот document_id действительно присутствует среди данных,
    полученных от инструментов.

    Не считай ошибкой сам факт, что document_id отсутствует в
    неструктурированном фрагменте tool output, если соответствующее
    изменение явно присутствует в структурированном результате инструмента.

    Не требуй от ответа перечисления всех partial-документов,
    если пользователь прямо не спрашивал о качестве извлечения.
    Но если в ответе есть раздел "предупреждения", существенные
    partial-ограничения следует указать.

39. Не требуй от ответа перечисления всех элементов current_conditions.

Для сравнительных запросов достаточно содержательного
агрегированного сравнения условий. Отсутствие отдельного
элемента current_conditions не является ошибкой, если ответ
корректно отражает основные различия и совпадения.

Не создавай замечание только потому, что отдельное условие
из current_conditions не было упомянуто в ответе.

Проверяй фактическую корректность утверждений, а не полное
покрытие всех элементов tool result.

40. Не требуй исчерпывающего перечисления условий, если пользователь
не запросил полный перечень условий договора.

Если пользователь просит "какие условия есть", разрешено
сгруппировать близкие условия и дать содержательное резюме,
вместо перечисления каждой записи current_conditions.

ВАЖНО:

Если ответ не выполняет запрос пользователя, passed должно быть false.

Если обнаружена хотя бы одна существенная фактическая ошибка,
passed должно быть false.

Если проблема только в стиле или формулировке и фактическое
содержание корректно, passed может быть true.

Не исправляй ответ самостоятельно.
Только оцени его и перечисли конкретные проблемы.

Если ты перечислил хотя бы одну проблему в поле issues,
которая требует исправления ответа, passed должно быть false.

Не допускается комбинация:
passed=true при наличии существенной проблемы в issues.
"""


class AgentReflection:
    def __init__(self):
        if FOLDER_ID:
            model = ChatOpenAI(
                model=MODEL,
                base_url=BASE_URL,
                api_key=API_KEY,
                temperature=0,
                default_headers={
                    "OpenAI-Project": FOLDER_ID
                },
            )
        else:
            model = ChatOpenAI(
                model=MODEL,
                base_url=BASE_URL,
                api_key=API_KEY,
                temperature=0,
            )

        self.llm = model.with_structured_output(
            ReflectionResult
        )

    def check(
        self,
        query: str,
        answer: str,
        tool_results: str,
    ) -> ReflectionResult:
        prompt = f"""
{REFLECTION_PROMPT}

ИСХОДНЫЙ ЗАПРОС ПОЛЬЗОВАТЕЛЯ:
{query}

ИТОГОВЫЙ ОТВЕТ АГЕНТА:
{answer}

РЕЗУЛЬТАТЫ ИНСТРУМЕНТОВ:
{tool_results}
"""

        try:
            result = self.llm.invoke(prompt)
        except Exception as e:
            print(
                "[REFLECTION] Ошибка API:",
                type(e).__name__,
                str(e),
            )

            return ReflectionResult(
                passed=False,
                issues=[
                    "Автоматическая Reflection-проверка не выполнена "
                    f"из-за ошибки API: {type(e).__name__}"
                ],
            )

        return result
